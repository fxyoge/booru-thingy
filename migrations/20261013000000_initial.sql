CREATE TABLE user_settings (
    id bigint PRIMARY KEY CHECK (id = 1),
    blacklisted_tags text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
