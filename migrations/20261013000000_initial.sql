CREATE TABLE media_assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256 text NOT NULL UNIQUE,
    md5 text NOT NULL,
    file_ext text NOT NULL,
    content_type text NOT NULL,
    file_size bigint NOT NULL CHECK (file_size > 0),
    image_width integer NOT NULL CHECK (image_width > 0),
    image_height integer NOT NULL CHECK (image_height > 0),
    duration double precision,
    original_key text NOT NULL,
    processing_version integer NOT NULL DEFAULT 1,
    status text NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'active', 'error')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX media_assets_md5 ON media_assets(md5);
CREATE TABLE media_variants (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    media_asset_id bigint NOT NULL REFERENCES media_assets(id),
    kind text NOT NULL,
    object_key text NOT NULL,
    file_ext text NOT NULL,
    content_type text NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    file_size bigint NOT NULL,
    UNIQUE(media_asset_id, kind)
);
CREATE TABLE posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_asset_id bigint NOT NULL UNIQUE REFERENCES media_assets(id),
    source text NOT NULL DEFAULT '',
    rating text NOT NULL DEFAULT 'g' CHECK (rating IN ('g', 's', 'q', 'e')),
    parent_id bigint REFERENCES posts(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (parent_id IS DISTINCT FROM id)
);
CREATE INDEX posts_parent ON posts(parent_id);
CREATE TABLE tags (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (name <> ''),
    category integer NOT NULL DEFAULT 0 CHECK (category IN (0, 1, 3, 4, 5)),
    post_count bigint NOT NULL DEFAULT 0 CHECK (post_count >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX tags_prefix ON tags(name text_pattern_ops);
CREATE TABLE post_tags (
    post_id bigint NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    tag_id bigint NOT NULL REFERENCES tags(id),
    PRIMARY KEY(post_id, tag_id)
);
CREATE INDEX post_tags_tag ON post_tags(tag_id, post_id);
CREATE TABLE favorites (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL UNIQUE REFERENCES posts(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE uploads (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source text NOT NULL DEFAULT '',
    referer_url text NOT NULL DEFAULT '',
    tag_string text NOT NULL DEFAULT 'tagme',
    rating text NOT NULL DEFAULT 'g' CHECK (rating IN ('g', 's', 'q', 'e')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE upload_items (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    upload_id bigint NOT NULL REFERENCES uploads(id),
    filename text NOT NULL DEFAULT '',
    source_url text NOT NULL DEFAULT '',
    input_key text,
    input_etag text,
    task_id text,
    media_asset_id bigint REFERENCES media_assets(id),
    post_id bigint REFERENCES posts(id),
    duplicate boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((input_key IS NULL) = (input_etag IS NULL))
);
CREATE INDEX upload_items_upload ON upload_items(upload_id);
CREATE TABLE web_sessions (
    token_hash text PRIMARY KEY,
    csrf_token text NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
